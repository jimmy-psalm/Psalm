def has(n, *needles):
    m = META[n]
    blob = " ".join([m["primary"], m["tags"], m["author"], m["bg"], m["sit"], m["theme"]])
    return any(s in blob for s in needles)


def take(pool, needed, pred=None):
    out = []
    for n in list(pool):
        if len(out) >= needed:
            break
        if pred is None or pred(n):
            out.append(n)
            pool.remove(n)
    return out


def assign_category(name, seeds):
    """seeds: {label: [psalm numbers]}. Remaining filled to target counts."""
    assigned = {}
    used = set()
    for label, nums in seeds.items():
        want = TARGETS[name][label]
        picked = []
        for n in nums:
            if n not in used and n in ALL:
                picked.append(n)
                used.add(n)
            if len(picked) >= want:
                break
        for n in picked:
            assigned[n] = label
    leftover = [n for n in ALL if n not in used]
    remaining = {
        label: TARGETS[name][label] - sum(1 for v in assigned.values() if v == label)
        for label in TARGETS[name]
    }
    # fill largest remaining labels first so leftovers go to high-count tags
    for label, need in sorted(remaining.items(), key=lambda kv: -kv[1]):
        if need <= 0:
            continue
        got = leftover[:need]
        leftover = leftover[need:]
        for n in got:
            assigned[n] = label
            used.add(n)
        remaining[label] -= len(got)
    missing = [n for n in ALL if n not in assigned]
    if missing:
        raise SystemExit(f"{name} missing {missing}")
    counts = Counter(assigned.values())
    for label, want in TARGETS[name].items():
        if counts[label] != want:
            raise SystemExit(f"{name}/{label} got {counts[label]} want {want}")
    return assigned


